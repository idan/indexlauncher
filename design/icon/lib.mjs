// Geometry and renderers for the Index Launcher icon. build.mjs holds the chosen parameters.
//
// Everything is laid out on Android's 108×108dp adaptive-icon canvas. Launchers show the
// central 72dp (18–90) through their mask, and nothing inside the 66dp circle is ever cropped.

const CAP_HEIGHT = 705; // Nunito's cap height in font units
const INK = '#F8F7FF';

const r = (n) => Math.round(n * 100) / 100;
const roundPath = (d) => d.replace(/-?\d+\.?\d*(e-?\d+)?/g, (m) => String(r(Number(m))));
const alphaHex = (o) => Math.round(o * 255).toString(16).padStart(2, '0').toUpperCase();

/** Places the ↓ A/Z mark for a parameter set. See ICON in build.mjs for what each one means. */
export function layout(font, p) {
	const H = p.markHeight;
	const v = font.getVariation({ wght: p.weight });
	const [A, Z, I] = 'AZI'.split('').map((ch) => v.glyphsForString(ch)[0]);

	const capH = H * p.capRatio;
	const s = capH / CAP_HEIGHT;
	const stroke = (I.bbox.maxX - I.bbox.minX) * s; // the arrow matches the letters' stems
	const reach = H * p.headRatio; // each arrowhead arm's horizontal (and vertical) reach
	const gap = H * p.gapRatio;
	const column = Math.max(A.bbox.maxX - A.bbox.minX, Z.bbox.maxX - Z.bbox.minX) * s;
	const arrowWidth = 2 * reach + stroke;
	const width = arrowWidth + gap + column;
	const left = 54 - width / 2;
	const top = 54 - H / 2;
	const bottom = 54 + H / 2;

	// Raise the Z toward the A, optionally re-centre the pair, and end the arrow `peek` dp
	// below the Z's baseline.
	const shift = p.centerLetters ? 54 - (top + bottom - p.zLift) / 2 : 0;
	const aBaseline = top + capH + shift;
	const zBaseline = bottom - p.zLift + shift;
	const arrowBottom = zBaseline + p.peek;

	const x = left + arrowWidth / 2;
	const tip = arrowBottom - stroke / 2;
	const shaftTop = p.arrow.fromEdge ? 0 : top + stroke / 2;
	const arrowPath = `M${r(x)},${r(shaftTop)}V${r(tip)}M${r(x - reach)},${r(tip - reach)}L${r(x)},${r(tip)}L${r(x + reach)},${r(tip - reach)}`;

	const columnCenter = left + arrowWidth + gap + column / 2;
	const letter = (g, baseline) => {
		const cx = (g.bbox.minX + g.bbox.maxX) / 2;
		// Font units are y-up: flip, scale to cap height, and set the baseline.
		return roundPath(g.path.transform(s, 0, 0, -s, columnCenter - cx * s, baseline).toSVG());
	};

	return {
		...p,
		stroke: r(stroke),
		arrowPath,
		a: letter(A, aBaseline),
		z: letter(Z, zBaseline),
		fade: { x: r(x), y1: r(p.arrow.fromEdge ? p.arrow.fadeStartY : top), y2: r(arrowBottom) },
	};
}

/** Foreground artwork as SVG elements. `id` keeps gradient IDs unique within one HTML page. */
export function foregroundSvg(L, { color = INK, id = 'fade' } = {}) {
	const { x, y1, y2 } = L.fade;
	return [
		`<defs><linearGradient id="${id}" x1="${x}" y1="${y1}" x2="${x}" y2="${y2}" gradientUnits="userSpaceOnUse">`,
		`<stop offset="0" stop-color="${color}" stop-opacity="${L.arrow.from}" />`,
		`<stop offset="1" stop-color="${color}" stop-opacity="${L.arrow.to}" />`,
		`</linearGradient></defs>`,
		`<path d="${L.arrowPath}" fill="none" stroke="url(#${id})" stroke-width="${L.stroke}" stroke-linecap="round" stroke-linejoin="round" />`,
		`<path d="${L.a}" fill="${color}" />`,
		`<path d="${L.z}" fill="${color}" />`,
	].join('');
}

const backgroundGradientSvg = (id, [from, to]) =>
	`<linearGradient id="${id}" x1="0" y1="0" x2="108" y2="108" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="${from}" /><stop offset="1" stop-color="${to}" /></linearGradient>`;

/** Website icon: the visible 72dp area with rounded corners. */
export function webIcon(L, gradient) {
	return `<!-- Generated by design/icon/build.mjs. Edit the parameters there, not this file. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">
	<defs>
		${backgroundGradientSvg('bg', gradient)}
		<clipPath id="shape"><rect x="18" y="18" width="72" height="72" rx="20" /></clipPath>
	</defs>
	<g clip-path="url(#shape)">
		<rect width="108" height="108" fill="url(#bg)" />
		${foregroundSvg(L)}
	</g>
</svg>
`;
}

